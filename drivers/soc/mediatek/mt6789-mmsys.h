#ifndef __SOC_MEDIATEK_MT6789_MMSYS_H
#define __SOC_MEDIATEK_MT6789_MMSYS_H

#define MT6789_MMSYS_SW0_RST_B 0x160

#define MT6789_MMSYS_DL_VALID0 0xe9c
#define MT6789_MMSYS_DL_VALID1 0xea0
#define MT6789_MMSYS_DL_READY0 0xea8
#define MT6789_MMSYS_DL_READY1 0xeac
#define MT6789_MMSYS_SMI_LARB0_GREQ 0x8dc
#define MT6789_MMSYS_SMI_LARB1_GREQ 0x8e0

#define MT6789_MMSYS_OVL_CON 0xf04
#define MT6789_MMSYS_OVL_CON_MASK GENMASK(3, 0)
#define MT6789_MMSYS_OVL_CON_OVL0_GO_BLEND BIT(0)

#define MT6789_DISP_OVL0_2L_MOUT 0xf14
#define MT6789_DISP_OVL0_MOUT 0xf18

/* OVL0 and OVL0_2L Routes are shared */
#define MT6789_DISP_OVL_MOUT_MASK       GENMASK(2, 0)
#define MT6789_DISP_OVL_MOUT_TO_RDMA0    BIT(0)
#define MT6789_DISP_OVL_MOUT_TO_RSZ0    BIT(1)
#define MT6789_DISP_OVL_MOUT_TO_WDMA0    BIT(2)

#define MT6789_DISP_RDMA0_SEL_IN 0xf28
#define MT6789_DISP_RDMA0_FROM_MASK     GENMASK(2, 0)
#define MT6789_DISP_RDMA0_FROM_OVL0    (0 << 0)
#define MT6789_DISP_RDMA0_FROM_RSZ0    (1 << 0)
#define MT6789_DISP_RDMA0_FROM_OVL0_2L (2 << 0)

#define MT6789_DISP_DSI0_SEL_IN    0xf30
#define MT6789_DISP_DSI0_FROM_MASK    GENMASK(2, 0)
#define MT6789_DISP_DSI0_FROM_RDMA_RSZ0   (0 << 0)
#define MT6789_DISP_DSI0_FROM_DITHER0    (1 << 0)
#define MT6789_DISP_DSI0_FROM_DSC0    (2 << 0)

/* Dither Output Multiplex */
#define MT6789_DISP_DITHER0_MOUT 0xf20
#define MT6789_DISP_DITHER0_MOUT_MASK    GENMASK(2, 0)
#define MT6789_DISP_DITHER0_MOUT_TO_DSI0    BIT(0)
#define MT6789_DISP_DITHER0_MOUT_TO_WDMA0    BIT(1)
#define MT6789_DISP_DITHER0_MOUT_TO_DSC0    BIT(2)

/* RDMA Output Selection (Looks like it goes only through RSZ0) */
#define MT6789_DISP_RDMA0_RSZ0_SOUT    0xf0c
#define MT6789_DISP_RDMA0_RSZ0_MASK    GENMASK(1, 0)
#define MT6789_DISP_RDMA0_RSZ0_SOUT_TO_DSI0    (0 << 0)
#define MT6789_DISP_RDMA0_RSZ0_SOUT_TO_COLOR0    (1 << 0)

/* DSC0 Output Multiplex */
#define MT6789_DISP_DSC0_MOUT    0xf38
#define MT6789_DISP_DSC0_MOUT_MASK    GENMASK(1, 0)
#define MT6789_DISP_DSC0_MOUT_TO_WDMA0    BIT(0)
#define MT6789_DISP_DSC0_MOUT_TO_DSI0    BIT(1)

/* NOTE: upstream-donor bug fixed here. These two entries selected the RDMA0
 * input mux but wrote it into the OVL MOUT register (0xf18/0xf14) instead of
 * DISP_RDMA0_SEL_IN (0xf28). Since mtk_mmsys_update_bits() is a
 * read-modify-write and mtk-mmsys.c applies EVERY matching route in array
 * order, the value 0 with GENMASK(2,0) cleared the MOUT_TO_RDMA0 bit that the
 * preceding entry had just set -- leaving OVL0 unrouted and the panel black.
 */
static const struct mtk_mmsys_routes mmsys_mt6789_routing_table[] = {
	/* OVL0 Routes */
	/*
	 * LK leaves the factory OVL0_2L -> OVL0 cascade selected here (0x9).
	 * The maintained path starts at OVL0, so replace the complete low-nibble
	 * topology instead of preserving OVL0_2L as OVL0's background source.
	 */
	MMSYS_ROUTE(OVL0, RDMA0, MT6789_MMSYS_OVL_CON,
		    MT6789_MMSYS_OVL_CON_MASK,
		    MT6789_MMSYS_OVL_CON_OVL0_GO_BLEND),
	MMSYS_ROUTE(OVL0, RDMA0, MT6789_DISP_OVL0_MOUT,
		    MT6789_DISP_OVL_MOUT_MASK,
		    MT6789_DISP_OVL_MOUT_TO_RDMA0),
	//MMSYS_ROUTE(OVL0, RSZ0, MT6789_DISP_OVL0_MOUT, MT6789_DISP_OVL_MOUT_TO_RSZ0, MT6789_DISP_OVL_MOUT_TO_RSZ0),
	MMSYS_ROUTE(OVL0, WDMA0, MT6789_DISP_OVL0_MOUT, MT6789_DISP_OVL_MOUT_TO_WDMA0, MT6789_DISP_OVL_MOUT_TO_WDMA0),
	MMSYS_ROUTE(OVL0, RDMA0, MT6789_DISP_RDMA0_SEL_IN, MT6789_DISP_RDMA0_FROM_MASK, MT6789_DISP_RDMA0_FROM_OVL0),
	/* OVL0_2L Routes */
	MMSYS_ROUTE(OVL_2L0, RDMA0, MT6789_DISP_OVL0_2L_MOUT, MT6789_DISP_OVL_MOUT_TO_RDMA0, MT6789_DISP_OVL_MOUT_TO_RDMA0),
	//MMSYS_ROUTE(OVL_2L0, RSZ0, MT6789_DISP_OVL0_2L_MOUT, MT6789_DISP_OVL_MOUT_TO_RSZ0, MT6789_DISP_OVL_MOUT_TO_RSZ0),
	MMSYS_ROUTE(OVL_2L0, WDMA0, MT6789_DISP_OVL0_2L_MOUT, MT6789_DISP_OVL_MOUT_TO_WDMA0, MT6789_DISP_OVL_MOUT_TO_WDMA0),
	MMSYS_ROUTE(OVL_2L0, RDMA0, MT6789_DISP_RDMA0_SEL_IN, MT6789_DISP_RDMA0_FROM_MASK, MT6789_DISP_RDMA0_FROM_OVL0_2L),
	/* RDMA0 Routes (looks like it goes through RSZ0) */
	MMSYS_ROUTE(RDMA0, DSI0, MT6789_DISP_RDMA0_RSZ0_SOUT, MT6789_DISP_RDMA0_RSZ0_MASK, MT6789_DISP_RDMA0_RSZ0_SOUT_TO_DSI0),
	MMSYS_ROUTE(RDMA0, DSI0, MT6789_DISP_DSI0_SEL_IN, MT6789_DISP_DSI0_FROM_MASK, MT6789_DISP_DSI0_FROM_RDMA_RSZ0),
	/* The direct path must remove every inherited PQ/DSC output branch. */
	MMSYS_ROUTE(RDMA0, DSI0, MT6789_DISP_DITHER0_MOUT,
		    MT6789_DISP_DITHER0_MOUT_MASK, 0),
	MMSYS_ROUTE(RDMA0, DSI0, MT6789_DISP_DSC0_MOUT,
		    MT6789_DISP_DSC0_MOUT_MASK, 0),
	MMSYS_ROUTE(RDMA0, COLOR0, MT6789_DISP_RDMA0_RSZ0_SOUT, MT6789_DISP_RDMA0_RSZ0_MASK, MT6789_DISP_RDMA0_RSZ0_SOUT_TO_COLOR0),
	/* Looks like COLOR0 goes to DITHER0, so no input selection */
	/*
	 * LK leaves DITHER0 routed to both DSI0 and DSC0 (0x5).  DSC0 is not
	 * part of the 60 Hz non-DSC path and is not clocked, so preserving that
	 * stale branch holds the DDP ready chain low and OVL0 underflows forever.
	 * MOUT is an output selection, not a one-bit enable: replace all three
	 * output bits when selecting the direct DSI0 path.
	 */
	MMSYS_ROUTE(DITHER0, DSI0, MT6789_DISP_DITHER0_MOUT,
		    MT6789_DISP_DITHER0_MOUT_MASK,
		    MT6789_DISP_DITHER0_MOUT_TO_DSI0),
	MMSYS_ROUTE(DITHER0, DSI0, MT6789_DISP_DSI0_SEL_IN, MT6789_DISP_DSI0_FROM_MASK, MT6789_DISP_DSI0_FROM_DITHER0),
	MMSYS_ROUTE(DITHER0, WDMA0, MT6789_DISP_DITHER0_MOUT, MT6789_DISP_DITHER0_MOUT_TO_WDMA0, MT6789_DISP_DITHER0_MOUT_TO_WDMA0),
	MMSYS_ROUTE(DITHER0, DSC0, MT6789_DISP_DITHER0_MOUT, MT6789_DISP_DITHER0_MOUT_TO_DSC0, MT6789_DISP_DITHER0_MOUT_TO_DSC0),
	/* DSC0 Routes */
	MMSYS_ROUTE(DSC0, WDMA0, MT6789_DISP_DSC0_MOUT, MT6789_DISP_DSC0_MOUT_TO_WDMA0, MT6789_DISP_DSC0_MOUT_TO_WDMA0),
	MMSYS_ROUTE(DSC0, DSI0, MT6789_DISP_DSC0_MOUT,
		    MT6789_DISP_DSC0_MOUT_MASK,
		    MT6789_DISP_DSC0_MOUT_TO_DSI0),
	MMSYS_ROUTE(DSC0, DSI0, MT6789_DISP_DSI0_SEL_IN, MT6789_DISP_DSI0_FROM_MASK, MT6789_DISP_DSI0_FROM_DSC0),
};

#endif /* __SOC_MEDIATEK_MT6789_MMSYS_H */
